        private static readonly EcCurve[] AllCurves =
        [
            NistP256, NistP384, NistP521, BrainpoolP256r1, BrainpoolP384r1, BrainpoolP512r1,
        ];

        private readonly byte[] _oid;

        private EcCurve(string name, byte[] oid, string p, string a, string b, string gx, string gy, string n)
        {
            Name = name;
            _oid = oid;
            P = ParseHex(p);
            A = ParseHex(a);
            B = ParseHex(b);
            Gx = ParseHex(gx);
            Gy = ParseHex(gy);
            N = ParseHex(n);
            FieldByteLength = (BigIntegerMath.BitLength(P) + 7) / 8;
            OrderBitLength = BigIntegerMath.BitLength(N);
        }

        /// <summary>Every curve this library knows, in a fixed order.</summary>
        public static IReadOnlyList<EcCurve> All => AllCurves;

        /// <summary>A human-readable curve name, for diagnostics only.</summary>
        public string Name { get; }

        /// <summary>
        /// The OID's DER <em>content</em> octets - without the 0x06 tag and length byte - which is
        /// exactly how RFC 9580 §5.5.5.4 (and RFC 6637 §9 before it) stores the curve in a key
        /// packet: a one-octet length followed by these bytes. Returns a fresh copy each time so
        /// callers cannot mutate the curve table.
        /// </summary>
        public byte[] Oid => (byte[])_oid.Clone();

        /// <summary>The field prime p.</summary>
        public BigInteger P { get; }

        /// <summary>The curve coefficient a. Not -3 for the brainpool curves, so the arithmetic must handle a general a.</summary>
        public BigInteger A { get; }

        /// <summary>The curve coefficient b.</summary>
        public BigInteger B { get; }

        /// <summary>The base point's affine x coordinate.</summary>
        public BigInteger Gx { get; }

        /// <summary>The base point's affine y coordinate.</summary>
        public BigInteger Gy { get; }

        /// <summary>The prime order n of the base point (and, with cofactor 1, of the whole curve group).</summary>
        public BigInteger N { get; }

        /// <summary>The fixed byte length of one encoded field element/coordinate: ceil(bitlen(p) / 8) per SEC 1 v2 §2.3.5.</summary>
        public int FieldByteLength { get; }

        /// <summary>bitlen(n): how many leftmost digest bits ECDSA keeps (FIPS 186-5 §6.4.1).</summary>
        public int OrderBitLength { get; }

        /// <summary>Finds a curve by its OID content octets (see <see cref="Oid"/>), or <c>null</c> if the curve is unknown or unsupported.</summary>
        public static EcCurve? FindByOid(byte[] oid)
        {
            if (oid == null)
            {
                return null;
            }

            foreach (EcCurve curve in AllCurves)
            {
                if (BytesEqual(curve._oid, oid))
                {
                    return curve;
                }
            }

            return null;
        }

        /// <summary>
        /// Whether the affine point (x, y) is a valid finite point of this curve: both coordinates
        /// are canonical field elements in [0, p) and satisfy y² ≡ x³ + ax + b (mod p) - the
        /// checks of SEC 1 v2 §3.2.2.1 steps 2-3 (step 4, n·Q = O, is implied by h = 1).
        /// </summary>
        public bool IsOnCurve(BigInteger x, BigInteger y)
        {
            if (x.Sign < 0 || x >= P || y.Sign < 0 || y >= P)
            {
                return false;
            }

            BigInteger left = BigInteger.Remainder(y * y, P);
            BigInteger right = BigInteger.Remainder((((x * x) + A) * x) + B, P);
            return left == right;
        }

        /// <inheritdoc />
        public override string ToString() => Name;

        private static BigInteger ParseHex(string hex)
        {
            // A leading "0" keeps BigInteger's two's-complement hex parser from reading a value
            // whose top nibble is >= 8 as negative.
            return BigInteger.Parse("0" + hex, NumberStyles.AllowHexSpecifier, CultureInfo.InvariantCulture);
        }

        private static bool BytesEqual(byte[] a, byte[] b)
        {
            if (a.Length != b.Length)
            {
                return false;
            }

            for (int i = 0; i < a.Length; i++)
            {
                if (a[i] != b[i])
                {
                    return false;
                }
            }

            return true;
        }
