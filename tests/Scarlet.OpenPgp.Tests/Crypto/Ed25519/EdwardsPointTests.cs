using System.Numerics;
using Scarlet.OpenPgp.Crypto.Ed25519;

namespace Scarlet.OpenPgp.Tests.Crypto.Ed25519
{
    public class EdwardsPointTests
    {
        [Fact]
        public void BasePoint_ShouldBeOnTheCurve()
        {
            // Assert
            Assert.True(EdwardsPoint.B.IsOnCurve);
        }

        [Fact]
        public void Identity_ShouldBeOnTheCurve()
        {
            // Assert
            Assert.True(EdwardsPoint.Identity.IsOnCurve);
        }

        [Fact]
        public void Add_BasePointAndIdentity_ShouldReturnBasePoint()
        {
            // Act
            EdwardsPoint result = EdwardsPoint.B.Add(EdwardsPoint.Identity);

            // Assert
            Assert.Equal(EdwardsPoint.B, result);
        }

        [Fact]
        public void Add_BasePointToItself_ShouldEqualScalarMultiplyByTwo()
        {
            // Act
            EdwardsPoint doubled = EdwardsPoint.B.Add(EdwardsPoint.B);
            EdwardsPoint scaled = EdwardsPoint.B.ScalarMultiply(2);

            // Assert
            Assert.Equal(doubled, scaled);
            Assert.True(doubled.IsOnCurve);
        }

        [Fact]
        public void ScalarMultiply_ByGroupOrder_ShouldReturnIdentity()
        {
            // Arrange: L = 2^252 + 27742317777372353535851937790883648493 is the order of the
            // subgroup generated by B, so [L]B must be the identity.
            BigInteger groupOrderL = BigInteger.Pow(2, 252) + BigInteger.Parse("27742317777372353535851937790883648493");

            // Act
            EdwardsPoint result = EdwardsPoint.B.ScalarMultiply(groupOrderL);

            // Assert
            Assert.Equal(EdwardsPoint.Identity, result);
        }

        [Fact]
        public void ScalarMultiply_IsConsistentWithRepeatedAddition()
        {
            // Act
            EdwardsPoint viaScalar = EdwardsPoint.B.ScalarMultiply(5);
            EdwardsPoint viaAddition = EdwardsPoint.B.Add(EdwardsPoint.B).Add(EdwardsPoint.B).Add(EdwardsPoint.B).Add(EdwardsPoint.B);

            // Assert
            Assert.Equal(viaScalar, viaAddition);
        }
    }
}
